import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import {readFile,writeFile,unlink} from 'node:fs/promises';

const url='https://schulpilot.dorfspy.de';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/opt/google/chrome/chrome',timeout:15000,args:['--no-sandbox']});
const parent=await browser.newContext({viewport:{width:1440,height:1000}});
const child=await browser.newContext({viewport:{width:1280,height:1000}});
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const checks=[]; const errors=[];
let demo; let passed=false;
const accountFile='../artifacts/.qa-account.json';
try{demo=JSON.parse(await readFile(accountFile,'utf8'));}catch{}
const headers={'X-Schulpilot-Request':'1'};
async function typeField(page,label,value){await page.getByRole('textbox',{name:label,exact:false}).click();await page.waitForTimeout(250);await page.keyboard.type(value,{delay:50});await page.waitForTimeout(150);}
async function accessible(page){
  await page.locator('flt-semantics-placeholder').evaluateAll(nodes=>nodes.forEach(node=>node.click()));
  await page.waitForTimeout(300);
}
for(const ctx of [parent,child,mobile]) ctx.on('page',page=>page.on('pageerror',error=>errors.push(error.message)));
try{
  const p=await parent.newPage();
  await p.goto(url,{waitUntil:'domcontentloaded'});
  await p.waitForSelector('flutter-view'); await accessible(p);
  if(!demo){
    const created=p.waitForResponse(r=>r.url().endsWith('/api/demo')&&r.request().method()==='POST');
    await p.getByRole('button',{name:'Synthetisch ausprobieren',exact:true}).click();
    demo=await (await created).json();
    assert.equal(demo.token,undefined,'web login must use HttpOnly cookies');
    await writeFile(accountFile,JSON.stringify(demo),{mode:0o600});
  }else{
    const result=await parent.request.post(url+'/api/auth/login',{headers,data:{username:demo.credentials.parent_username,password:demo.credentials.parent_password}});
    assert.equal(result.status(),200);await p.goto(url+'/app',{waitUntil:'domcontentloaded'});await p.waitForSelector('flutter-view');await accessible(p);
  }
  await p.getByText('Deine Familie im Blick.',{exact:true}).waitFor();
  await p.getByRole('button',{name:'Ansehen',exact:true}).waitFor();
  const cookie=(await parent.cookies()).find(c=>c.name==='sp_session');
  assert(cookie?.secure&&cookie?.httpOnly&&cookie.sameSite==='Strict');
  await p.screenshot({path:'../artifacts/public-parent.png'});
  checks.push('parent dashboard and secure cookie'); console.log('parent dashboard passed');
  let unitId=demo.unitId;
  if(!unitId){
    await p.getByRole('button',{name:'Ansehen',exact:true}).click();
    await p.getByLabel('Materialien',{exact:true}).click();
    await p.getByRole('button',{name:'Stoff & Unsicherheiten bestätigen',exact:true}).click();
    await p.mouse.move(1100,750);await p.mouse.wheel(0,1100);await p.waitForTimeout(400);
    const checkbox=p.getByRole('checkbox',{name:/Ich habe den Stoff geprüft/});
    await checkbox.click();await p.waitForTimeout(300);
    assert.equal(await checkbox.getAttribute('aria-checked'),'true');
    await p.getByRole('button',{name:'Stoff bestätigen',exact:true}).click();
    await p.getByRole('button',{name:'Lerneinheit für das Kind vorbereiten',exact:true}).click();
    await p.getByRole('button',{name:'Projektstatus',exact:true}).waitFor();
    for(let retry=0;retry<20;retry++){const overview=await(await parent.request.get(url+'/api/children/'+demo.child_id+'/overview')).json();if(overview.units.length){unitId=overview.units[0].id;break;}await p.waitForTimeout(500);}
    assert(unitId,'unit must be generated by the material action');
    demo.unitId=unitId;await writeFile(accountFile,JSON.stringify(demo),{mode:0o600});
  }
  const authoritative=await (await parent.request.get(url+'/api/units/'+unitId)).json();
  assert.equal(authoritative.questions.length,4);
  checks.push('material confirmation and durable unit generation through UI'); console.log('material workflow passed');
  const c=await child.newPage();
  await c.goto(url+'/login',{waitUntil:'domcontentloaded'});await c.waitForSelector('flutter-view');await accessible(c);
  await c.getByRole('textbox',{name:'E-Mail oder Kinder-Benutzername',exact:true}).click();await c.waitForTimeout(300);await c.keyboard.type(demo.credentials.child_username,{delay:40});
  await c.getByLabel('Passwort',{exact:true}).click();await c.waitForTimeout(300);await c.keyboard.type(demo.credentials.child_password,{delay:40});await c.waitForTimeout(200);
  await c.getByRole('button',{name:'Anmelden',exact:true}).click();
  await c.getByRole('button',{name:'Jetzt lernen',exact:true}).waitFor();
  if(authoritative.status==='completed'){await c.goto(url+'/unit/'+unitId,{waitUntil:'domcontentloaded'});await c.waitForSelector('flutter-view');await accessible(c);}else{
    await c.getByRole('button',{name:'Jetzt lernen',exact:true}).click();
    await c.getByRole('button',{name:'Ein Hinweis bitte',exact:true}).waitFor();
    if(authoritative.questions[0].hints_used===0)await c.getByRole('button',{name:'Ein Hinweis bitte',exact:true}).click();
  }
  for(const q of authoritative.questions){
    if(q.attempts.some(a=>a.outcome==='correct'||a.outcome==='uncertain')||q.attempts.length>=3)continue;
    await c.getByRole('button',{name:'Antwort prüfen',exact:true}).waitFor();
    if(q.type==='choice') await c.getByRole('button',{name:q.answer}).first().click();
    if(q.type==='gap') await typeField(c,'Deine Ergänzung',q.answer);
    if(q.type==='short') await typeField(c,'Deine kurze Antwort',q.answer);
    if(q.type==='match'){
      for(const pair of q.options){const [left,right]=pair.split('|');await c.getByRole('button',{name:left}).or(c.getByRole('combobox',{name:left})).or(c.getByLabel(left)).first().click();await c.getByText(right,{exact:true}).or(c.getByLabel(right,{exact:true})).last().click();}
    }
    const answerResponse=c.waitForResponse(r=>r.url().endsWith('/questions/'+q.id+'/answer')&&r.request().method()==='POST');
    await c.getByRole('button',{name:'Antwort prüfen',exact:true}).click();
    const result=await answerResponse;assert.equal(result.status(),200);assert.equal((await result.json()).outcome,'correct');console.log('exercise passed',q.type);
  }
  await c.getByRole('button',{name:'Zu meinem Tag',exact:true}).waitFor();
  await c.screenshot({path:'../artifacts/public-child-completed.png'});
  checks.push('independent child browser login and four interactive exercise widgets'); console.log('child exercises passed');
  await p.goto(url+'/child/'+demo.child_id,{waitUntil:'domcontentloaded'});await p.waitForSelector('flutter-view');await accessible(p);await p.getByLabel('Lernverlauf',{exact:true}).click();
  const stored=await (await parent.request.get(url+'/api/children/'+demo.child_id+'/overview')).json();assert.equal(stored.day_summary.answer_count,4);assert(stored.day_summary.hints_used>=1);
  await p.screenshot({path:'../artifacts/public-parent-history.png'});
  checks.push('saved answers visible in parent history');
  const m=await mobile.newPage();await m.goto(url,{waitUntil:'domcontentloaded'});await m.waitForSelector('flutter-view');await accessible(m);
  await m.getByRole('button',{name:'Synthetisch ausprobieren',exact:true}).waitFor();
  await m.screenshot({path:'../artifacts/public-mobile.png'});
  checks.push('mobile landing at 390 px');
  assert.deepEqual(errors,[],'browser runtime errors');
  passed=true;
  console.log(JSON.stringify({url,checks,external_ai_calls:0,runtime_errors:errors},null,2));
} finally {
  if(demo&&passed){await parent.request.delete(url+'/api/account',{headers,data:{password:demo.credentials.parent_password}});await unlink(accountFile);}
  await browser.close();
}
